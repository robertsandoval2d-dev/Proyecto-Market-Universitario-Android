@Composable
fun AdminReportsScreen() {
    Column(
        modifier = Modifier
            .fillMaxSize()
            .padding(horizontal = 16.dp)
    ) {
        Spacer(modifier = Modifier.height(12.dp))

        Text(
            text = "Incidencias y Reportes de la Comunidad",
            fontSize = 14.sp,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            modifier = Modifier.padding(bottom = 16.dp)
        )

        LazyColumn(
            modifier = Modifier.fillMaxSize(),
            verticalArrangement = Arrangement.spacedBy(12.dp),
            contentPadding = PaddingValues(bottom = 16.dp)
        ) {
            item {
                ReportCardPlaceholder(
                    title = "Producto sospechoso reportado",
                    detail = "El usuario @estudiante1 reportó un ítem por categoría incorrecta o contenido indebido.",
                    tag = "Pendiente"
                )
            }
            item {
                ReportCardPlaceholder(
                    title = "Comentario inapropiado en reseña",
                    detail = "Reporte en la sección de valoraciones del negocio 'Café Campus'.",
                    tag = "En Revisión"
                )
            }
            item {
                ReportCardPlaceholder(
                    title = "Uso indebido de la marca",
                    detail = "Alerta automática del sistema por coincidencia de nombre.",
